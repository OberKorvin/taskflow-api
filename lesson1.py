# 1. ПЕРЕМЕННЫЕ (Коробки с данными)
# Мы кладем данные в "коробку" с именем слева от знака =
task_title = "Настроить сервер"      # Текст (всегда в кавычках) - тип str (string)
priority = 1                         # Целое число (без кавычек) - тип int (integer)
is_completed = False                 # Правда или Ложь (True / False) - тип bool (boolean)

# Команда print() выводит на экран в терминал то, что написано у нее в скобках
print("Название задачи:", task_title)


# 2. СЛОВАРЬ / DICTIONARY (Карточка объекта)
# В фигурных скобках {} мы храним полную карточку одной задачи в формате "ключ": значение.
# Именно в таком виде (он называется JSON) сайты и серверы пересылают данные друг другу!
single_task = {
    "id": 101,
    "title": "Выучить базу Python",
    "completed": False
}

# Чтобы достать одно поле из словаря, мы пишем его ключ в квадратных скобках:
print("Статус задачи №101:", single_task["title"])


# 3. СПИСОК / LIST (Полка с несколькими объектами)
# В квадратных скобках [] через запятую мы храним много элементов подряд.
all_tasks = [
    {"id": 1, "title": "Купить чай", "completed": True},
    {"id": 2, "title": "Написать первый код", "completed": False},
    {"id": 3, "title": "Проверить терминал", "completed": False},
    {"id": 4, "title": "Jod", "completed": False}
]

print("Всего задач в списке:", len(all_tasks))  # len() считает количество элементов


print("--- СПИСОК ВСЕХ ЗАДАЧ ---")

# 4. ЦИКЛ (for) И УСЛОВИЕ (if)
# Мы говорим Python: "Возьми каждую задачу (назовем её временно task) из списка all_tasks"
for task in all_tasks:
    # Проверяем условие: если поле "completed" равно True (выполнено)
    if task["completed"] == True:
        status = "✅ Готово"
    else:  # Иначе (если False)
        status = "⏳ В работе"
    
    # f перед кавычками (f-строка) позволяет вставлять переменные прямо внутрь текста в скобках {}
    print(f"Задача #{task['id']}: {task['title']} — {status}")


# 5. ФУНКЦИЯ (def) — Многоразовая команда
# Мы создаем свою собственную команду find_task_by_id, которой нужно передать номер (task_id)
def find_task_by_id(task_id):
    for task in all_tasks:
        if task["id"] == task_id:
            return task  # Как только нашли нужную задачу — сразу возвращаем её и выходим
    
    return None  # Если проверили весь список и ничего не нашли — возвращаем Пустоту (None)


print("--- ПРОВЕРКА ПОИСКА ---")
# Вызываем нашу функцию: просим найти задачу под номером 2
found = find_task_by_id(2)
print("Результат поиска задачи №2:", found)


